export function contentTypeOf(path: string): string {
  const base = path.slice(path.lastIndexOf("/") + 1);
  const dot = base.lastIndexOf(".");
  return (dot >= 0 && KNOWN[base.slice(dot).toLowerCase()]) || "application/octet-stream";
}
